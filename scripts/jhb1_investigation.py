def _text(path: str) -> str:
    import re, html as H
    h = (ROOT / path).read_text(errors="ignore")
    h = re.sub(r"<(script|style)[^>]*>.*?</\1>", " ", h, flags=re.S | re.I)
    t = re.sub(r"\s+", " ", H.unescape(re.sub(r"<[^>]+>", " ", h)))
    return t


def _attempts(which: str, name: str) -> list:
    """Collect retrieval attempts across both fetch logs."""
    out = []
    for log in ("jhb1_fetch_log.json", "airtrunk_fetch_log.json"):
        d = json.loads((RAW / log).read_text())
        if name in d:
            e = dict(d[name])
            e.setdefault("ts", e.get("attempted_at"))
            if e.get("status") is not None:
                e["outcome"] = f"http_{e['status']}"
            elif e.get("error"):
                e["outcome"] = "error"
            out.append(e)
    if which == "generated":
        out.append({"ts": "2026-10-31", "outcome": "generated",
                    "note": "analysis artifact generated by scripts/jhb1_investigation.py"})
    return out


def _fy24_text() -> str:
    """Extract the FY24 report text once to a sidecar file (deterministic)."""
    out = ROOT / "data/raw/jhb1_fy24_report.txt"
    if not out.exists():
        from pypdf import PdfReader
        r = PdfReader(RAW / "jhb1_fy24_sustainability_pdf.pdf")
        out.write_text("\n".join((p.extract_text() or "") for p in r.pages))
    return out.read_text()


